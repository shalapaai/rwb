OPERATOR_KOP_PER_HOUR = 25000  # час сотрудника ПВЗ с взносами


def labour_kop(minutes: int) -> int:
    """Себестоимость работы сотрудника, копейки (целочисленное округление до копейки)."""
    return (minutes * OPERATOR_KOP_PER_HOUR + 30) // 60
